// The replayer's own stylesheet, embedded so it can live inside <pitwall-player>'s shadow root
// (a document-level stylesheet would not reach in there).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const cssPath = require.resolve('@rrweb/replay/dist/style.css');
const css = readFileSync(cssPath, 'utf8');
writeFileSync(
  new URL('../src/ui/rrweb-style.ts', import.meta.url),
  `// Generated by scripts/embed-rrweb-css.mjs from @rrweb/replay/dist/style.css. Do not edit.\nimport { unsafeCSS } from 'lit';\n\nexport const rrwebStyle = unsafeCSS(${JSON.stringify(css)});\n`,
);
